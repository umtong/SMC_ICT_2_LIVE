def from_transcript_api(video_id: str) -> tuple[list[dict[str, Any]], str, str, str] | None:
    result = base.transcript_api_fallback(video_id)
    if result is None:
        return None
    segments, source = result
    return segments, source, "unknown", "fallback"


def save_transcript(record: base.VideoRecord, output_root: Path, result: tuple[list[dict[str, Any]], str, str, str]) -> base.VideoRecord:
    segments, source, language, kind = result
    clean: list[dict[str, Any]] = []
    for item in segments:
        text = base.normalized_text(str(item.get("text") or ""))
        if text:
            clean.append(
                {
                    "start": round(float(item.get("start") or 0.0), 3),
                    "duration": round(max(0.0, float(item.get("duration") or 0.0)), 3),
                    "text": text,
                }
            )
    text = "\n".join(item["text"] for item in clean).strip()
    if not text:
        record.transcript_status = "missing"
        record.error = "all caption methods parsed to empty text"
        return record
    channel_dir = output_root / "transcripts" / record.channel_key
    channel_dir.mkdir(parents=True, exist_ok=True)
    json_path = channel_dir / f"{record.video_id}.json"
    txt_path = channel_dir / f"{record.video_id}.txt"
    payload = {
        "schema_version": 2,
        "channel_key": record.channel_key,
        "channel_name": record.channel_name,
        "video_id": record.video_id,
        "title": record.title,
        "webpage_url": record.webpage_url,
        "upload_date": record.upload_date,
        "duration_seconds": record.duration_seconds,
        "source": source,
        "language": language,
        "kind": kind,
        "segments": clean,
    }
    json_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    txt_path.write_text(text + "\n", encoding="utf-8")
    record.transcript_status = "ok"
    record.transcript_source = source
    record.transcript_language = language
    record.transcript_kind = kind
    record.transcript_segments = len(clean)
    record.transcript_characters = len(text)
    record.transcript_sha256 = hashlib.sha256(text.encode("utf-8")).hexdigest()
    record.transcript_path = str(txt_path.relative_to(output_root))
    return record


def process(record: base.VideoRecord, output_root: Path) -> base.VideoRecord:
    time.sleep(random.uniform(0.05, 0.3))
    methods = (from_innertube, from_timedtext, from_transcript_api, from_piped, from_invidious)
    errors: list[str] = []
    for method in methods:
        try:
            result = method(record.video_id)
            if result is not None:
                return save_transcript(record, output_root, result)
        except Exception as exc:
            errors.append(f"{method.__name__} {type(exc).__name__}: {exc}")
    record.transcript_status = "missing"
    record.error = "; ".join(errors) or "no public caption returned by five independent methods"
    return record


