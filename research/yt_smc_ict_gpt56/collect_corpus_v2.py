def parse_response(response: requests.Response) -> list[dict[str, Any]]:
    if not response.content:
        return []
    text = response.text
    content_type = response.headers.get("content-type", "").lower()
    try:
        if "json" in content_type or text.lstrip().startswith("{"):
            return base.parse_json3(response.json())
        if text.lstrip().startswith("WEBVTT"):
            return base.parse_vtt(text)
        return base.parse_xmlish(text)
    except Exception:
        return []


def language_code(track: dict[str, Any]) -> str:
    return str(
        track.get("languageCode")
        or track.get("lang_code")
        or track.get("lang")
        or track.get("code")
        or ""
    )


def rank_tracks(tracks: list[dict[str, Any]]) -> list[dict[str, Any]]:
    def score(track: dict[str, Any]) -> tuple[int, int, str]:
        language = language_code(track)
        if language in LANG_PRIORITY:
            language_rank = LANG_PRIORITY.index(language)
        elif language.startswith("ko"):
            language_rank = len(LANG_PRIORITY)
        elif language.startswith("en"):
            language_rank = len(LANG_PRIORITY) + 1
        else:
            language_rank = len(LANG_PRIORITY) + 2
        automatic = bool(track.get("autoGenerated")) or str(track.get("kind") or "") == "asr"
        return language_rank, int(automatic), language

    return sorted([track for track in tracks if isinstance(track, dict)], key=score)


def fetch_track(session: requests.Session, url: str) -> list[dict[str, Any]]:
    separator = "&" if "?" in url else "?"
    candidates = [f"{url}{separator}fmt=json3", url]
    for candidate in candidates:
        try:
            response = session.get(candidate, timeout=40)
            response.raise_for_status()
            segments = parse_response(response)
            if segments:
                return segments
        except Exception:
            continue
    return []


def from_innertube(video_id: str) -> tuple[list[dict[str, Any]], str, str, str] | None:
    endpoint = f"https://www.youtube.com/youtubei/v1/player?key={INNERTUBE_KEY}&prettyPrint=false"
    session = requests.Session()
    session.headers.update(headers())
    for client in INNERTUBE_CLIENTS:
        try:
            response = session.post(
                endpoint,
                json={
                    "context": {"client": client},
                    "videoId": video_id,
                    "contentCheckOk": True,
                    "racyCheckOk": True,
                },
                timeout=35,
            )
            response.raise_for_status()
            data = response.json()
            tracks = (
                data.get("captions", {})
                .get("playerCaptionsTracklistRenderer", {})
                .get("captionTracks", [])
            )
            for track in rank_tracks(tracks):
                url = str(track.get("baseUrl") or "")
                if not url:
                    continue
                segments = fetch_track(session, url)
                if segments:
                    kind = str(track.get("kind") or ("asr" if track.get("isTranslatable") else "manual"))
                    return segments, f"youtube-innertube:{client['clientName']}", language_code(track) or "unknown", kind
        except Exception:
            continue
    return None


def from_timedtext(video_id: str) -> tuple[list[dict[str, Any]], str, str, str] | None:
    hosts = (
        "https://www.youtube.com/api/timedtext",
        "https://video.google.com/timedtext",
        "https://www.youtube-nocookie.com/api/timedtext",
    )
    session = requests.Session()
    session.headers.update(headers())
    requests_to_try: list[tuple[str, dict[str, str]]] = []
    for host in hosts:
        try:
            listing = session.get(host, params={"type": "list", "v": video_id, "hl": "ko"}, timeout=20)
            listing.raise_for_status()
            if listing.text.strip():
                root = ET.fromstring(listing.text)
                tracks = [dict(node.attrib) for node in root.iter() if node.tag.rsplit("}", 1)[-1] == "track"]
                for track in rank_tracks(tracks):
                    params = {
                        "v": video_id,
                        "lang": track.get("lang_code") or track.get("lang") or "ko",
                        "fmt": "json3",
                    }
                    if track.get("kind"):
                        params["kind"] = str(track["kind"])
                    if track.get("name"):
                        params["name"] = str(track["name"])
                    requests_to_try.append((host, params))
        except Exception:
            pass
        for language in ("ko", "ko-KR", "en"):
            requests_to_try.append((host, {"v": video_id, "lang": language, "fmt": "json3"}))
            requests_to_try.append((host, {"v": video_id, "lang": language, "kind": "asr", "fmt": "json3"}))
    seen: set[str] = set()
    for host, params in requests_to_try:
        marker = host + "?" + urllib.parse.urlencode(sorted(params.items()))
        if marker in seen:
            continue
        seen.add(marker)
        try:
            response = session.get(host, params=params, timeout=25)
            response.raise_for_status()
            segments = parse_response(response)
            if segments:
                return segments, "youtube-direct-timedtext", params.get("lang", "unknown"), params.get("kind", "manual")
        except Exception:
            continue
    return None


