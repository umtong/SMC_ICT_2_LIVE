def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Resilient complete YouTube caption collector.")
    parser.add_argument("--output", type=Path, default=Path("artifact/corpus"))
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--limit", type=int, default=0)
    parser.add_argument("--self-test", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    if args.self_test:
        self_test()
        return 0
    started_at = base.utc_now()
    output: Path = args.output
    output.mkdir(parents=True, exist_ok=True)
    enumerated: list[base.VideoRecord] = []
    enumeration_errors: list[dict[str, str]] = []
    for channel in base.CHANNELS:
        for tab in base.TAB_NAMES:
            try:
                enumerated.extend(base.enumerate_tab(channel, tab))
            except Exception as exc:
                enumeration_errors.append(
                    {
                        "channel_key": channel["channel_key"],
                        "channel_name": channel["display_name"],
                        "tab": tab,
                        "error": f"{type(exc).__name__}: {exc}",
                    }
                )
    records = base.merge_records(enumerated)
    if args.limit > 0:
        records = [
            record
            for channel in base.CHANNELS
            for record in [item for item in records if item.channel_key == channel["channel_key"]][-args.limit :]
        ]
    (output / "ENUMERATION_ERRORS.json").write_text(
        json.dumps(enumeration_errors, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(f"[{base.utc_now()}] v2 unique videos: {len(records)}", flush=True)
    processed: list[base.VideoRecord] = []
    with cf.ThreadPoolExecutor(max_workers=max(1, min(args.workers, 6))) as executor:
        futures = {executor.submit(process, record, output): record for record in records}
        for index, future in enumerate(cf.as_completed(futures), start=1):
            result = future.result()
            processed.append(result)
            print(
                f"[{base.utc_now()}] {index}/{len(records)} {result.channel_name} {result.video_id} "
                f"{result.transcript_status} source={result.transcript_source} chars={result.transcript_characters} {result.title[:80]}",
                flush=True,
            )
    processed.sort(key=lambda item: (item.channel_key, item.timestamp or 0, item.upload_date or "", item.video_id))
    summary = base.write_outputs(processed, output, started_at)
    summary["collector_version"] = 2
    (output / "CORPUS_SUMMARY.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2, sort_keys=True), flush=True)
    return 3 if enumeration_errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
